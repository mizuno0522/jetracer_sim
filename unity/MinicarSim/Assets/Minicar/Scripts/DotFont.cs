        /// 文字列の幅 (文字の高さ h に対して)
        public static float Width(string t, float h) => t.Length * h * 6f / 7f;

        /// (a, b) が文字列の中か。a = 読む向きの位置 (左端 0)、b = 下端からの高さ、h = 文字の高さ
        public static bool At(string t, float a, float b, float h)
        {
            if (a < 0f || b < 0f || b >= h) return false;
            float cw = h * 6f / 7f;                     // 1 文字の送り (5 点 + 間 1 点)
            int k = (int)(a / cw);
            if (k >= t.Length || !kGlyphs.TryGetValue(t[k], out var g)) return false;
            int col = (int)((a - k * cw) / (h / 7f)), row = 6 - (int)(b / (h / 7f));
            return col < 5 && row >= 0 && row < 7 && ((g[row] >> (4 - col)) & 1) != 0;
        }
    }
}
